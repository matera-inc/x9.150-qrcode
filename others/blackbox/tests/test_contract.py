"""Every length, pattern and required constraint in openapi.yaml, refused (Story 3.3).

The cases are generated by ``contract.py`` from the contract itself; nobody typed them. Each one
asserts three things:

- **400**;
- **the field's path** in the violations (``creditor.address.city``, with real array indices);
- **nothing changed**: no QR Code created, the patched QR Code's revision and ETag unmoved, its
  status unmoved, nothing delivered to a payee.

A control per operation proves the unbroken sample is accepted; without it, a service that refused
everything would pass every case. Known gaps (``contract-known-gaps.yaml``) run as strict
expected failures, and the run ends with how many cases were generated, executed and skipped
(S3.3-AC3).
"""
import pytest

import contract
from x9client import samples
from x9client.samples import BILL, PAYER_WALLET, RECIPIENT, TX_HASH

CASES = contract.cases()
GAPS = contract.known_gaps()
DEAD_PAYEE = "http://127.0.0.1:9/pub/api/v1/payment-notification"


def _notification(qr_id, *, post):
    note = {"payment": {"qrcodeId": qr_id, "amount": BILL, "currency": "USDC",
                        "network": "solana"},
            "payer": {"info": "contract@example.com"},
            "blockchain": {"action": "SENT" if post else "PAYMENT_INITIATED",
                           "from": PAYER_WALLET, "to": RECIPIENT}}
    if post:
        note["payment"]["transactionId"] = TX_HASH
    return {"endpoint": DEAD_PAYEE, "correlationId": "8a652794-9e73-4fd7-a628-4d525b638cbc",
            "notification": note}


@pytest.fixture(scope="module")
def full_qr(api):
    """One QR Code made from the full sample. Refused PATCHes must leave it exactly as it is."""
    request = samples.full_payment_request()
    created = api.post("/api/v1/payment-request", body=request)
    assert created.status == 201, f"the full sample must be accepted: {created}"
    return created.body["id"], request


def _base(operation, api, full_qr):
    qr_id, request = full_qr
    return {
        "create": lambda: samples.full_payment_request(),
        "patch": lambda: samples.full_patch(request),
        "status-update": lambda: {"status": "PAID", "network": "solana", "endToEndId": "E2E-C-1"},
        "pre-payment": lambda: _notification(qr_id, post=False),
        "post-payment": lambda: _notification(qr_id, post=True),
        "signature-validate": lambda: {"content": "a.b.c"},
        "emv-decoder": lambda: {"qrCode": "000201"},
    }[operation.name]()


def _send(api, operation, body, qr_id):
    path = operation.path.replace("{id}", qr_id)
    if operation.name == "patch":
        return api.patch(path, body=body, if_match=api.qr(qr_id).etag)
    return api.call(operation.method, path, body=body)


# ------------------------------------------------------------------ the generator itself

def test_a_new_constraint_gets_its_case_without_anyone_typing_it():
    """S3.3-AC1 — add a maxLength to the contract and a case for it appears; every kind is
    generated; every known gap names a case that exists (a stale entry would hide nothing)."""
    spec = contract.load()
    before = {c.id for c in contract.cases(spec)}
    spec["components"]["schemas"]["StatusUpdate"]["properties"]["blackboxProbe"] = {
        "type": "string", "maxLength": 3}

    added = {c.id for c in contract.cases(spec)} - before

    assert added == {"status-update:blackboxProbe:maxLength"}
    assert {c.kind for c in CASES} == set(contract.KINDS)
    assert set(GAPS) <= {c.id for c in CASES}, f"stale known gaps: {set(GAPS) - {c.id for c in CASES}}"


# ------------------------------------------------------------------ controls

@pytest.mark.parametrize("name, accepted", [
    ("create", {201}), ("patch", {200}), ("pre-payment", {502}), ("post-payment", {502}),
])
def test_the_unbroken_sample_is_accepted(api, full_qr, name, accepted):
    """S3.3-AC1 — the control: the sample every case breaks is itself accepted.

    For the payer-side operations "accepted" is 502: the request was valid and this service
    tried to deliver it to a payee that does not exist. A 400 is what a broken case must get.
    """
    operation = next(o for o in contract.OPERATIONS if o.name == name)
    response = _send(api, operation, _base(operation, api, full_qr), full_qr[0])
    assert response.status in accepted, f"{name}: the unbroken sample was refused: {response}"


# ------------------------------------------------------------------ the generated cases

def _param(case):
    marks = []
    if case.id in GAPS:
        marks.append(pytest.mark.xfail(reason=f"known gap: {GAPS[case.id]}", strict=True))
    return pytest.param(case, id=case.id, marks=marks)


@pytest.mark.parametrize("case", [_param(c) for c in CASES])
def test_a_contract_constraint_is_refused(api, full_qr, case):
    """S3.3-AC1 — one generated case: 400, the field's path, and no state change."""
    qr_id = full_qr[0]
    operation = case.operation
    try:
        body, field = case.build(_base(operation, api, full_qr))
    except contract.Unbuildable as e:
        pytest.skip(f"contract case not buildable: {e}")

    target = qr_id
    if operation.name == "status-update":
        target = api.create_qr()
    before = api.qr(target)

    response = _send(api, operation, body, target)

    assert response.status == 400, f"{case.id}: expected 400, got {response.status}: {response.body}"
    named = " ".join(str(v) for v in response.violations)
    assert field in named, f"{case.id}: refused, but not naming {field}: {response.body}"

    if operation.name == "create":
        assert not (isinstance(response.body, dict) and response.body.get("id")), \
            "a refused create must not create a QR Code"
    elif operation.name in ("patch", "status-update"):
        after = api.qr(target)
        assert after.etag == before.etag, f"a refused {operation.name} moved the ETag"
        assert after.body.get("revision") == before.body.get("revision")
        assert after.body.get("status") == before.body.get("status")
